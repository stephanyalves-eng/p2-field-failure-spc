"""Download FAA Service Difficulty Reports and keep the Airbus A320 family, ATA chapter 24.

Source: FAA, "Download Service Difficulty Reports (SDR) by Year",
https://www.faa.gov/av-info/download_SDR (one CSV per calendar year).

Usage:
    python -m src.data.download_faa_sdr            # download (if missing) and filter
    python -m src.data.download_faa_sdr --offline  # only filter files already in data/raw/faa_sdr

Output (git-ignored, regenerated by this script):
    data/processed/faa_sdr_a320_ata24.csv  one row per report
"""

from __future__ import annotations

import argparse
import urllib.request
from pathlib import Path

import pandas as pd

BASE_URL = "https://external.apic4e.faa.gov/sdrs/retrieve"
USER_AGENT = "p2-field-failure-spc research script"
YEARS = [2024, 2025]  # the two latest complete calendar years at extraction

ROOT = Path(__file__).resolve().parents[2]
RAW_DIR = ROOT / "data" / "raw" / "faa_sdr"
PROCESSED_DIR = ROOT / "data" / "processed"

# A318, A319, A320 and A321, including neo variants (model codes such as A321271NX).
A320_FAMILY = r"^A3(18|19|20|21)"
ATA_CHAPTER = "24"  # electrical power: JASC codes 2400-2497

# Aircraft registration and serial numbers are left out.
KEEP = [
    "OperatorControlNumber",
    "DifficultyDate",
    "JASCCode",
    "AircraftMake",
    "AircraftModel",
    "PartName",
    "PartCondition",
    "Discrepancy",
]


def download(year: int, dest_dir: Path = RAW_DIR) -> Path:
    """Download one yearly SDR file into dest_dir unless it is already there."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / f"SDR-{year}.csv"
    if dest.exists():
        return dest
    request = urllib.request.Request(
        f"{BASE_URL}/SDR-{year}.csv", headers={"User-Agent": USER_AGENT}
    )
    tmp = dest.with_suffix(".csv.part")
    with urllib.request.urlopen(request, timeout=300) as response, open(tmp, "wb") as out:
        while chunk := response.read(1 << 20):
            out.write(chunk)
    tmp.replace(dest)
    return dest


def read_sdr_csv(path: Path) -> pd.DataFrame:
    """Read a yearly SDR CSV with every field as text."""
    return pd.read_csv(path, dtype=str, keep_default_na=False, encoding="utf-8")


def filter_a320_ata24(df: pd.DataFrame) -> pd.DataFrame:
    """Keep Airbus A318-A321 reports with a JASC code in ATA chapter 24."""
    df = df.assign(
        AircraftMake=df["AircraftMake"].str.strip().str.upper(),
        AircraftModel=df["AircraftModel"].str.strip().str.upper(),
        PartName=df["PartName"].str.strip().str.upper(),
        JASCCode=df["JASCCode"].str.strip(),
    )
    mask = (
        df["AircraftMake"].eq("AIRBUS")
        & df["AircraftModel"].str.match(A320_FAMILY)
        & df["JASCCode"].str.startswith(ATA_CHAPTER)
    )
    return df.loc[mask, KEEP].reset_index(drop=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--offline", action="store_true", help="skip downloads")
    args = parser.parse_args()

    frames = []
    for year in YEARS:
        path = RAW_DIR / f"SDR-{year}.csv" if args.offline else download(year)
        frames.append(filter_a320_ata24(read_sdr_csv(path)))
    reports = pd.concat(frames, ignore_index=True).drop_duplicates("OperatorControlNumber")

    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    reports.to_csv(PROCESSED_DIR / "faa_sdr_a320_ata24.csv", index=False)
    print(f"A320 family, ATA 24: {len(reports)} reports")
    print(reports["JASCCode"].value_counts().to_string())


if __name__ == "__main__":
    main()
