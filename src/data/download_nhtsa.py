"""Download NHTSA complaint and recall flat files and keep the scoped EV models.

Source: NHTSA Office of Defects Investigation flat files, https://static.nhtsa.gov/odi/ffdd/
Field layouts: CMPL.txt (complaints) and RCL.txt (recalls) in the same folders.

Usage:
    python -m src.data.download_nhtsa            # download (if missing) and filter
    python -m src.data.download_nhtsa --offline  # only filter files already in data/raw/nhtsa

Outputs (git-ignored, regenerated by this script):
    data/processed/nhtsa_complaints.csv  one row per complaint and component
    data/processed/nhtsa_recalls.csv     one row per recall campaign, model year and component
"""

from __future__ import annotations

import argparse
import csv
import io
import urllib.request
import zipfile
from pathlib import Path

import pandas as pd

BASE_URL = "https://static.nhtsa.gov/odi/ffdd"
USER_AGENT = "p2-field-failure-spc research script"

ROOT = Path(__file__).resolve().parents[2]
RAW_DIR = ROOT / "data" / "raw" / "nhtsa"
PROCESSED_DIR = ROOT / "data" / "processed"

# Complaint files are split by the date NHTSA received the complaint. 2015 onward covers
# every model year of the four vehicles below (the oldest is the 2017 Bolt EV).
COMPLAINT_FILES = [
    "cmpl/COMPLAINTS_RECEIVED_2015-2019.zip",
    "cmpl/COMPLAINTS_RECEIVED_2020-2024.zip",
    "cmpl/COMPLAINTS_RECEIVED_2025-2026.zip",
]
RECALL_FILES = ["rcl/FLAT_RCL_POST_2010.zip"]

# (MAKETXT, MODELTXT) exactly as written in the flat files. Variants such as IONIQ 5 N
# and BOLT EUV are separate models and are left out on purpose.
MODELS = [
    ("HYUNDAI", "IONIQ 5"),
    ("FORD", "MUSTANG MACH E"),
    ("TESLA", "MODEL 3"),
    ("CHEVROLET", "BOLT EV"),
]

# Field order from CMPL.txt (51 fields, last updated April 30, 2026).
COMPLAINT_COLUMNS = [
    "CMPLID", "ODINO", "MFR_NAME", "MAKETXT", "MODELTXT", "YEARTXT", "CRASH", "FAILDATE",
    "FIRE", "INJURED", "DEATHS", "COMPDESC", "CITY", "STATE", "VIN", "DATEA", "LDATE",
    "MILES", "OCCURENCES", "CDESCR", "CMPL_TYPE", "POLICE_RPT_YN", "PURCH_DT",
    "ORIG_OWNER_YN", "ANTI_BRAKES_YN", "CRUISE_CONT_YN", "NUM_CYLS", "DRIVE_TRAIN",
    "FUEL_SYS", "FUEL_TYPE", "TRANS_TYPE", "VEH_SPEED", "DOT", "TIRE_SIZE", "LOC_OF_TIRE",
    "TIRE_FAIL_TYPE", "ORIG_EQUIP_YN", "MANUF_DT", "SEAT_TYPE", "RESTRAINT_TYPE",
    "DEALER_NAME", "DEALER_TEL", "DEALER_CITY", "DEALER_STATE", "DEALER_ZIP", "PROD_TYPE",
    "REPAIRED_YN", "MEDICAL_ATTN", "VEHICLES_TOWED_YN", "STATE_OF_INCIDENT",
    "VEHICLE_OPERATOR",
]  # fmt: skip

# Field order from RCL.txt (29 fields, last updated May 2025). CONEQUENCE_DEFECT is
# spelled as in the official layout.
RECALL_COLUMNS = [
    "RECORD_ID", "CAMPNO", "MAKETXT", "MODELTXT", "YEARTXT", "MFGCAMPNO", "COMPNAME",
    "MFGNAME", "BGMAN", "ENDMAN", "RCLTYPECD", "POTAFF", "ODATE", "INFLUENCED_BY", "MFGTXT",
    "RCDATE", "DATEA", "RPNO", "FMVSS", "DESC_DEFECT", "CONEQUENCE_DEFECT",
    "CORRECTIVE_ACTION", "NOTES", "RCL_CMPT_ID", "MFR_COMP_NAME", "MFR_COMP_DESC",
    "MFR_COMP_PTNO", "DO_NOT_DRIVE", "PARK_OUTSIDE",
]  # fmt: skip

# Columns kept for the analysis. Personal or location data (city, VIN, dealer, operator
# name) is dropped here and never written to data/processed.
COMPLAINT_KEEP = [
    "CMPLID", "ODINO", "MAKETXT", "MODELTXT", "YEARTXT", "COMPDESC", "FAILDATE", "LDATE",
    "MILES", "CRASH", "FIRE", "INJURED", "DEATHS", "VEHICLES_TOWED_YN", "CMPL_TYPE",
    "CDESCR",
]  # fmt: skip
RECALL_KEEP = [
    "CAMPNO", "MAKETXT", "MODELTXT", "YEARTXT", "COMPNAME", "MFGNAME", "MFGCAMPNO",
    "BGMAN", "ENDMAN", "POTAFF", "RCDATE", "INFLUENCED_BY", "DESC_DEFECT",
    "CONEQUENCE_DEFECT", "CORRECTIVE_ACTION", "MFR_COMP_NAME", "MFR_COMP_DESC",
    "DO_NOT_DRIVE", "PARK_OUTSIDE",
]  # fmt: skip


def download(relative_url: str, dest_dir: Path = RAW_DIR) -> Path:
    """Download one flat file into dest_dir unless it is already there."""
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / Path(relative_url).name
    if dest.exists():
        return dest
    request = urllib.request.Request(
        f"{BASE_URL}/{relative_url}", headers={"User-Agent": USER_AGENT}
    )
    tmp = dest.with_suffix(dest.suffix + ".part")
    with urllib.request.urlopen(request, timeout=300) as response, open(tmp, "wb") as out:
        while chunk := response.read(1 << 20):
            out.write(chunk)
    tmp.replace(dest)
    return dest


def read_flat_zip(path: Path, columns: list[str]) -> pd.DataFrame:
    """Read the single tab-delimited text file inside an NHTSA zip, every field as text."""
    with zipfile.ZipFile(path) as zf:
        (name,) = zf.namelist()
        with zf.open(name) as raw:
            return pd.read_csv(
                io.TextIOWrapper(raw, encoding="utf-8"),
                sep="\t",
                header=None,
                names=columns,
                dtype=str,
                keep_default_na=False,
                quoting=csv.QUOTE_NONE,
            )


def filter_models(df: pd.DataFrame, models: list[tuple[str, str]]) -> pd.DataFrame:
    """Keep rows whose make and model match one of the models exactly, after trim and upper."""
    df = df.assign(
        MAKETXT=df["MAKETXT"].str.strip().str.upper(),
        MODELTXT=df["MODELTXT"].str.strip().str.upper(),
    )
    wanted = pd.MultiIndex.from_tuples(models)
    mask = pd.MultiIndex.from_arrays([df["MAKETXT"], df["MODELTXT"]]).isin(wanted)
    return df[mask].reset_index(drop=True)


def build(files: list[str], columns: list[str], keep: list[str]) -> pd.DataFrame:
    frames = [filter_models(read_flat_zip(RAW_DIR / Path(f).name, columns), MODELS) for f in files]
    return pd.concat(frames, ignore_index=True)[keep]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--offline", action="store_true", help="skip downloads")
    args = parser.parse_args()

    if not args.offline:
        for f in COMPLAINT_FILES + RECALL_FILES:
            print(f"downloading {f}")
            download(f)

    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    complaints = build(COMPLAINT_FILES, COMPLAINT_COLUMNS, COMPLAINT_KEEP)
    # The yearly complaint files do not overlap, but drop exact repeats defensively.
    complaints = complaints.drop_duplicates(subset=["CMPLID"])
    recalls = build(RECALL_FILES, RECALL_COLUMNS, RECALL_KEEP).drop_duplicates()

    complaints.to_csv(PROCESSED_DIR / "nhtsa_complaints.csv", index=False)
    recalls.to_csv(PROCESSED_DIR / "nhtsa_recalls.csv", index=False)

    print(f"complaints: {len(complaints)} rows, {complaints['ODINO'].nunique()} complaints")
    print(f"recalls: {len(recalls)} rows, {recalls['CAMPNO'].nunique()} campaigns")
    print(complaints.groupby(["MAKETXT", "MODELTXT"])["ODINO"].nunique().to_string())
    print(recalls.groupby(["MAKETXT", "MODELTXT"])["CAMPNO"].nunique().to_string())


if __name__ == "__main__":
    main()
